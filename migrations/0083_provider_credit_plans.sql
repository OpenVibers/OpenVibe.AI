-- phase: expand
-- Monthly API credits that come with a subscription or a plan (2026-11-12, the owner: "make it aware of granted API
-- credits for both anthropic and openai"): ChatGPT Pro's $100, $200 or $500 a month of OpenAI API credit, an
-- Anthropic allowance, Altare Inference's $100 a month from 2026-12-01. Each plan becomes one promotional grant per
-- billing cycle in provider_credit_grants (applies_to 'plan:<id>:<cycle start>', expiring when the cycle ends), so
-- the router spends it first and nothing carries over; the first cycle is prorated when the plan starts mid-cycle.
CREATE TABLE IF NOT EXISTS provider_credit_plans (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_key text COLLATE "C" NOT NULL,
    label text COLLATE "C" NOT NULL,
    monthly_usd numeric(14, 6) NOT NULL CHECK (monthly_usd >= 0),
    renews_day integer NOT NULL CHECK (renews_day BETWEEN 1 AND 31),
    starts_on text COLLATE "C" NOT NULL,
    ends_on text COLLATE "C",
    prorate_first bigint NOT NULL DEFAULT 1,
    active bigint NOT NULL DEFAULT 1,
    notes text COLLATE "C",
    created_at text COLLATE "C" NOT NULL,
    updated_at text COLLATE "C" NOT NULL
);
CREATE INDEX IF NOT EXISTS provider_credit_plans_provider ON provider_credit_plans(provider_key, active);
