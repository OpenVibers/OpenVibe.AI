CREATE TABLE IF NOT EXISTS session_credentials (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner text COLLATE "C" NOT NULL,
    subject text COLLATE "C" NOT NULL,
    provider text COLLATE "C" NOT NULL,
    label text COLLATE "C" NOT NULL,
    secret_enc text COLLATE "C" NOT NULL,
    created_at text COLLATE "C" NOT NULL,
    last_used_at text COLLATE "C",
    expires_at text COLLATE "C",
    expired bigint NOT NULL DEFAULT 0,
    notified_expired bigint NOT NULL DEFAULT 0,
    settings_json text COLLATE "C" NOT NULL DEFAULT '{}',
    UNIQUE(owner, subject, provider)
);
CREATE INDEX IF NOT EXISTS session_credentials_subject ON session_credentials(owner, subject);
