CREATE TABLE IF NOT EXISTS provider_credit_grants (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_key text COLLATE "C" NOT NULL,
    kind text COLLATE "C" NOT NULL CHECK (kind IN ('promotional', 'purchased')),
    amount_usd numeric(14, 6) NOT NULL CHECK (amount_usd >= 0),
    as_of text COLLATE "C" NOT NULL,
    expires_at text COLLATE "C",
    applies_to text COLLATE "C",
    created_at text COLLATE "C" NOT NULL
);
CREATE INDEX IF NOT EXISTS provider_credit_grants_provider ON provider_credit_grants(provider_key, kind, as_of);
